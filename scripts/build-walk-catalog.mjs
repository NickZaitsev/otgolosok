import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const routesDirectory = join(root, "public", "data", "routes");
const outputPath = join(root, "backend", "builtin-routes.mjs");

const files = (await readdir(routesDirectory))
  .filter((name) => name.endsWith(".json"))
  .sort((a, b) => a.localeCompare(b, "en"));
const routes = [];
for (const file of files) {
  routes.push(JSON.parse(await readFile(join(routesDirectory, file), "utf8")));
}

const output = `// Generated by scripts/build-walk-catalog.mjs. Do not edit manually.\nexport const builtinRoutes = ${JSON.stringify(routes, null, 2)};\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error("backend/builtin-routes.mjs is out of date; run node scripts/build-walk-catalog.mjs");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, output);
}
